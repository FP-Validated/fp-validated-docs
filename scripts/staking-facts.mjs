#!/usr/bin/env node
// Renders the "Key facts" table of each delegator staking guide, and the chain comparison table on
// the staking overview page, from chains/<chain>/staking.yaml (schema:
// chains/_schema/staking.schema.json), so validator address, commission and timing rules live in
// one place.
//
//   node scripts/staking-facts.mjs           # check: fail if a page is out of date
//   node scripts/staking-facts.mjs --write   # rewrite the tables in place
//
// Dependencies are resolved from website/node_modules (js-yaml, ajv).
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(root, 'website', 'package.json'));
const yaml = require('js-yaml');
const Ajv2020 = require('ajv/dist/2020');

const STALE_DAYS = 90;
const write = process.argv.includes('--write');
const schema = JSON.parse(readFileSync(join(root, 'chains/_schema/staking.schema.json'), 'utf8'));
const validate = new Ajv2020({ allErrors: true, strict: false }).compile(schema);

const BEGIN = '<!-- staking-facts:begin (generated by scripts/staking-facts.mjs, do not edit) -->';
const END = '<!-- staking-facts:end -->';

const INDEX_BEGIN = '<!-- staking-index:begin (generated by scripts/staking-facts.mjs, do not edit) -->';
const INDEX_END = '<!-- staking-index:end -->';

const esc = (s) => String(s).replace(/\|/g, '\\|');

// Replaces the text between two markers. Returns null when the markers are missing.
function splice(src, begin, end, body) {
  const start = src.indexOf(begin);
  const stop = src.indexOf(end);
  if (start < 0 || stop < start) return null;
  return src.slice(0, start) + body + src.slice(stop + end.length);
}

// Writes or checks one generated block. Returns false when the page is missing markers or stale.
function sync(page, src, next, what) {
  if (next === null) {
    console.error(`${page}: missing ${what} markers`);
    return false;
  }
  if (next === src) return true;
  if (write) {
    writeFileSync(page, next);
    console.log(`${page}: updated`);
    return true;
  }
  console.error(`${page}: ${what} is out of date; run node scripts/staking-facts.mjs --write`);
  return false;
}

function table(s) {
  const rows = [
    ['Validator', `${esc(s.validator.name)}`],
    [s.validator.addressLabel ?? 'Validator address', `\`${s.validator.address}\``],
    ['Explorer', `[View on explorer](${s.validator.explorer})`],
    ['Commission', `${s.commission.value}${s.commission.changeNotice ? ` (${esc(s.commission.changeNotice)})` : ''}`],
    ['Minimum stake', esc(s.minStake)],
    ['Stake activation', esc(s.activation)],
    ['Unbonding period', esc(s.unbonding)],
    ['Reward frequency', esc(s.rewardFrequency)],
    ['Auto-compounding', typeof s.autoCompound === 'string' ? esc(s.autoCompound) : s.autoCompound ? 'Yes' : 'No'],
    ['Penalties', esc(s.penalties)],
    ['Wallets and apps', s.wallets.map((w) => (w.url ? `[${w.name}](${w.url})` : w.name)).join(', ')],
    ['Facts last verified', s.lastVerified],
  ];
  return [BEGIN, '', '| Item | Value |', '| --- | --- |', ...rows.map(([k, v]) => `| ${k} | ${v} |`), '', END].join('\n');
}

let failed = false;
const guides = [];
for (const chain of readdirSync(join(root, 'chains')).filter((d) => !d.startsWith('_'))) {
  const metaPath = join(root, 'chains', chain, 'staking.yaml');
  if (!existsSync(metaPath)) continue;
  const facts = yaml.load(readFileSync(metaPath, 'utf8'), { schema: yaml.JSON_SCHEMA });
  if (!validate(facts)) {
    console.error(`${metaPath}: schema errors`, validate.errors);
    failed = true;
    continue;
  }
  if (facts.chain !== chain) {
    console.error(`${metaPath}: chain ${facts.chain} does not match directory ${chain}`);
    failed = true;
    continue;
  }
  const page = join(root, 'website/docs/staking', `${chain}.md`);
  if (!existsSync(page)) {
    console.error(`${chain}: staking.yaml exists but ${page} does not`);
    failed = true;
    continue;
  }
  const src = readFileSync(page, 'utf8');
  if (!sync(page, src, splice(src, BEGIN, END, table(facts)), 'key facts table')) failed = true;
  const fm = /last_verified:\s*(\d{4}-\d{2}-\d{2})/.exec(src);
  if (fm && fm[1] !== facts.lastVerified) {
    console.error(`${page}: frontmatter last_verified ${fm[1]} != staking.yaml lastVerified ${facts.lastVerified}`);
    failed = true;
  }
  if (facts.delegationOpen) {
    guides.push({
      facts,
      position: Number(/sidebar_position:\s*(\d+)/.exec(src)?.[1] ?? 99),
      label: /sidebar_label:\s*(.+)/.exec(src)?.[1].trim() ?? chain,
      status: /status:\s*(\S+)/.exec(src)?.[1] ?? 'draft',
    });
  }
  const age = (Date.now() - Date.parse(facts.lastVerified)) / 86400000;
  if (age > STALE_DAYS) console.warn(`${chain}: staking facts last verified ${Math.floor(age)} days ago (limit ${STALE_DAYS})`);
}
// Overview page: one row per chain that accepts delegation, in sidebar order.
const indexPage = join(root, 'website/docs/staking/index.md');
const indexRows = guides
  .sort((a, b) => a.position - b.position)
  .map(({ facts: s, label, status }) => {
    const rewards = s.autoCompound === false ? 'Claim manually' : 'Added to your stake';
    const token = s.token ?? '';
    return `| ${label} | ${token} | ${s.commission.value} | ${esc(s.unbondingShort)} | ${rewards} | [Stake ${token || label}](/staking/${s.chain}) | ${status} |`;
  });
const indexTable = [
  INDEX_BEGIN,
  '',
  '| Network | Token | Commission | Wait to unstake | Rewards | Guide | Guide status |',
  '| --- | --- | --- | --- | --- | --- | --- |',
  ...indexRows,
  '',
  INDEX_END,
].join('\n');
const indexSrc = readFileSync(indexPage, 'utf8');
if (!sync(indexPage, indexSrc, splice(indexSrc, INDEX_BEGIN, INDEX_END, indexTable), 'chain comparison table')) failed = true;

process.exit(failed ? 1 : 0);
